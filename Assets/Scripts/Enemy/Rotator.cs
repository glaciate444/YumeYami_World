using UnityEngine;

public class Rotator : MonoBehaviour {
    public float rotationSpeed = 100f; // 回る速さ

    void Update(){
        // Z軸（2Dでの回転軸）を毎フレーム回し続ける
        transform.Rotate(0, 0, rotationSpeed * Time.deltaTime);
    }
}
